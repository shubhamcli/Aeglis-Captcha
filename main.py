@router.get("/analytics/overview", summary="Get Dashboard Analytics")
@limiter.limit("30/minute") #  Shielded
async def get_analytics_overview(
    request: Request,
    product: str = "captcha", 
    days: int = 7,
    user_id: str = Depends(get_current_user)
):
    """
    Retrieves aggregate statistics for the developer dashboard (Blocks, Passes, Total).
    Fetches ULTRA-FAST from the daily_stats table instead of raw logs.
    """
    try:
        # 1. Fetch site key for this user
        site_response = supabase_admin.table("captcha_sites").select("site_key").eq("user_id", user_id).execute()
        
        # --- GRACEFUL FALLBACK ---
        if not site_response.data:
            empty_chart_dict = {}
            for i in range(days - 1, -1, -1):
                date_str = (datetime.now(timezone.utc) - timedelta(days=i)).strftime('%Y-%m-%d')
                empty_chart_dict[date_str] = {"total": 0, "blocked": 0}
                
            return {
                "success": True,
                "product": product,
                "data": {
                    "total_requests": 0,
                    "threats_blocked": 0,
                    "success_rate": 100.0,
                    "avg_latency_ms": 0,
                    "graph_data": {
                        "labels": list(empty_chart_dict.keys()),
                        "total": [0] * days,
                        "blocked": [0] * days
                    }
                }
            }
        
        site_key = site_response.data[0]['site_key']

        # 2. Calculate date threshold (e.g., 7 days ago, formatted as YYYY-MM-DD)
        n_days_ago = (datetime.now(timezone.utc) - timedelta(days=days-1)).strftime('%Y-%m-%d')
        
        # 3. Fetch pre-calculated stats from our new trigger-backed table!
        response = supabase_admin.table("captcha_daily_stats") \
            .select("stat_date, total_requests, blocked_requests") \
            .eq("site_key", site_key) \
            .gte("stat_date", n_days_ago) \
            .execute()
            
        daily_stats = response.data or []
        
        # 4. Graph Data Generation (Zero-filled for last 7 days)
        chart_data_dict = {}
        for i in range(days - 1, -1, -1):
            date_str = (datetime.now(timezone.utc) - timedelta(days=i)).strftime('%Y-%m-%d')
            chart_data_dict[date_str] = {"total": 0, "blocked": 0}

        # 5. Populate chart data and calculate global totals
        global_total = 0
        global_blocked = 0
        
        for stat in daily_stats:
            # DB returns stat_date string like "2026-08-02"
            stat_date = stat.get("stat_date", "")
            if stat_date in chart_data_dict:
                t_req = stat.get("total_requests", 0)
                b_req = stat.get("blocked_requests", 0)
                
                chart_data_dict[stat_date]["total"] = t_req
                chart_data_dict[stat_date]["blocked"] = b_req
                
                global_total += t_req
                global_blocked += b_req

        # 6. Final Aggregations
        passed = global_total - global_blocked
        success_rate = round((passed / global_total * 100), 1) if global_total > 0 else 100.0

        graph_labels = list(chart_data_dict.keys())
        graph_total = [chart_data_dict[k]["total"] for k in graph_labels]
        graph_blocked = [chart_data_dict[k]["blocked"] for k in graph_labels]

        return {
            "success": True,
            "product": product,
            "data": {
                "total_requests": global_total,
                "threats_blocked": global_blocked,
                "success_rate": success_rate,
                "graph_data": {
                    "labels": graph_labels,
                    "total": graph_total,
                    "blocked": graph_blocked
                }
            }
        }
    except Exception as e:
        logger.error(f"Error fetching analytics overview: {e}")
        raise HTTPException(status_code=500, detail="Database fetch error")

@router.get("/analytics/logs", summary="Get Detailed Request Logs")
@limiter.limit("30/minute") #  Shielded
async def get_analytics_logs(
    request: Request,
    limit: int = 50,
    offset: int = 0,
    user_id: str = Depends(get_current_user)
):
    """
    Retrieves granular table logs for individual Captcha executions with total count.
    """
    try:
        site_response = supabase_admin.table("captcha_sites").select("site_key").eq("user_id", user_id).execute()
        
        # --- GRACEFUL FALLBACK (Fix) ---
        if not site_response.data:
            return {"success": True, "logs": [], "total_count": 0}
        
        site_key = site_response.data[0]['site_key']

        # Fetch total count for pagination
        count_res = supabase_admin.table("captcha_analytics_logs").select("id", count="exact").eq("site_key", site_key).execute()
        total_count = count_res.count if hasattr(count_res, 'count') and count_res.count is not None else 0
        if total_count == 0 and isinstance(count_res.data, list):
             total_count = len(count_res.data) 

        # Fetch Paginated Logs
        response = supabase_admin.table("captcha_analytics_logs") \
            .select("*") \
            .eq("site_key", site_key) \
            .order("created_at", desc=True) \
            .range(offset, offset + limit - 1) \
            .execute()
        
        return {
            "success": True,
            "logs": response.data or [],
            "total_count": total_count
        }
    except Exception as e:
        logger.error(f"Error fetching analytics logs: {e}")
        raise HTTPException(status_code=500, detail="Database fetch error")



