# BACKGROUND WORKER (ZERO-LATENCY LOGGING)

def save_log_to_supabase(site_key: str, session_id: str, log_data: Dict[str, Any]):
    """
    Background worker function to save the execution log to Supabase.
    This runs asynchronously and does not block the API response.
    """
    if not site_key or not log_data:
        return
        
    try:
        supabase_admin.table("captcha_analytics_logs").insert({
            "site_key": site_key,
            "session_id": session_id,
            "action_taken": log_data.get("action_taken"),
            "fail_reason": log_data.get("fail_reason")
        }).execute()
    except Exception as e:
        logger.error(f"Background task failed to save log for {site_key}: {e}")



