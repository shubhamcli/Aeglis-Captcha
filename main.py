@router.post("/challenge", summary="Phase 1-3: Generate Verification Challenge")
@limiter.limit("20/minute") # 🛡️ RATE LIMIT: 20 challenges per minute per IP
async def create_challenge(request: Request, payload: ChallengeRequest = ChallengeRequest()):
    """
    Called when the Aeglis widget loads on the frontend.
    Returns session ID, 3D WebGL render parameters, DOM map, and PoW challenge.
    """
    result = engine.create_challenge(payload.site_key)
    
    if not result.get("success"):
        if "Invalid site key" in result.get("error", ""):
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail=result.get("error")
            )
            
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, 
            detail="Failed to generate challenge"
        )
    return result

@router.post("/verify", summary="Verify Telemetry and PoW")
@limiter.limit("30/minute") # 🛡️ RATE LIMIT: Slightly higher for retries
async def verify_captcha(request: Request, payload: VerifyRequest, background_tasks: BackgroundTasks):
    """
    Called when the user interacts with the widget or background processing completes.
    Verifies hardware integrity, DOM trap avoidance, and PoW solution.
    """
    
    #  EXTRACT CLIENT IP FOR DATACENTER CHECK
    # X-Forwarded-For handles IPs if behind a proxy/load balancer
    client_ip = request.headers.get("X-Forwarded-For", request.client.host if request.client else "")
    if client_ip and "," in client_ip:
        client_ip = client_ip.split(",")[0].strip() # Get the original client IP

    try:
        payload_dict = payload.model_dump()
        #  PASSING IP TO THE ENGINE
        result = engine.process_verification(payload.session_id, payload_dict, payload.site_key, client_ip)
        
        # Extract log data if present and queue the background task
        log_data = result.pop("log_data", None)
        if log_data and payload.site_key:
            background_tasks.add_task(save_log_to_supabase, payload.site_key, payload.session_id, log_data)
        
        if not result.get("success"):
            if result.get("action") == "require_puzzle":
                return result
                
            if "already processed" in result.get("error", "").lower():
                return {"success": False, "error": "Session already processed"}
                
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN, 
                detail=result.get("error", "Verification failed")
            )
            
        return result
    except HTTPException as he:
        raise he
    except Exception as e:
        logger.error(f"Error in /verify endpoint: {str(e)}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, 
            detail="Internal verification error"
        )

@router.post("/puzzle-solve", summary="Phase 4: Verify Physics Puzzle Solution")
@limiter.limit("15/minute") #  RATE LIMIT
async def verify_puzzle(request: Request, payload: PuzzleSolveRequest, background_tasks: BackgroundTasks):
    """
    Called if the /verify endpoint triggers Phase 4.
    Validates the user's input against the generated physics puzzle parameters.
    """
    result = engine.verify_puzzle(payload.session_id, payload.answer, payload.site_key)
    
    # Extract log data if present and queue the background task
    log_data = result.pop("log_data", None)
    if log_data and payload.site_key:
        background_tasks.add_task(save_log_to_supabase, payload.site_key, payload.session_id, log_data)
    
    if not result.get("success"):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN, 
            detail=result.get("error", "Puzzle verification failed")
        )
        
    return result

@router.post("/siteverify", summary="B2B Token Verification")
@limiter.limit("100/minute") #  RATE LIMIT: High limit as this comes from customer's backend
async def site_verify(request: Request, payload: SiteVerifyRequest):
    """
    Called by the customer's backend server before processing form submissions.
    Validates the customer's Secret Key against Supabase and the user's verification token.
    """
    if not payload.secret_key.startswith("sk_live_"):
        return {"success": False, "error": "Invalid secret key format"}

    try:
        response = supabase_admin.table("captcha_sites").select("id, site_key").eq("secret_key", payload.secret_key).execute()
        if not response.data:
            return {"success": False, "error": "Unauthorized: Invalid Secret Key"}
            
    except Exception as e:
        logger.error(f"Supabase DB error during siteverify: {str(e)}")
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Database verification error")

    is_valid = engine.verify_site_token(payload.token)
    
    if is_valid:
        return {"success": True, "timestamp": time.time()}
    else:
        return {"success": False, "error": "Invalid, expired, or already used token"}


