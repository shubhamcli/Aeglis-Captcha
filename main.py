# BACKGROUND ENGINES (Captcha archival/cleanup copied from main.py)

def cleanup_old_captcha_logs():
    """
    Nightly Background Job: Runs at 2:00 AM
    1. Fetches logs older than 7 days.
    2. Groups them by site_key and creates a CSV archive.
    3. Uploads CSV to Supabase Storage ('captcha_archives' bucket).
    4. Deletes the old logs from the PostgreSQL database.
    """
    print("Starting nightly Captcha log cleanup and archiving...")
    try:
        # Calculate the exact timestamp for 7 days ago
        seven_days_ago = (datetime.now(timezone.utc) - timedelta(days=7)).isoformat()

        # 1. Fetch old logs 
        response = supabase_admin.table("captcha_analytics_logs") \
            .select("*") \
            .lt("created_at", seven_days_ago) \
            .execute()
            
        old_logs = response.data or []
        
        if not old_logs:
            print("No logs older than 7 days found. Cleanup complete.")
            return

        # Group logs by site_key so each customer gets their own CSV file
        logs_by_site = {}
        for log in old_logs:
            sk = log.get("site_key")
            if sk not in logs_by_site:
                logs_by_site[sk] = []
            logs_by_site[sk].append(log)

        # 2. Generate CSV and upload to Supabase Storage
        today_str = datetime.now(timezone.utc).strftime("%Y%m%d")
        
        for site_key, logs in logs_by_site.items():
            if not logs: continue
            
            # Create CSV in RAM (Memory buffer) to avoid saving files on server disk
            csv_buffer = io.StringIO()
            fieldnames = logs[0].keys()
            writer = csv.DictWriter(csv_buffer, fieldnames=fieldnames)
            
            writer.writeheader()
            writer.writerows(logs)
            
            # Define file path (e.g., pk_live_123/logs_archive_20260802.csv)
            file_path = f"{site_key}/logs_archive_{today_str}.csv"
            
            try:
                # Upload to Supabase Storage bucket named 'captcha_archives'
                supabase_admin.storage.from_("captcha_archives").upload(
                    path=file_path, 
                    file=csv_buffer.getvalue().encode('utf-8'),
                    file_options={"content-type": "text/csv", "upsert": "true"}
                )
                print(f"Archived {len(logs)} logs for {site_key}.")
            except Exception as upload_err:
                print(f"Failed to upload archive for {site_key}: {upload_err}")

        # 3. DELETE the old logs from the database
        del_response = supabase_admin.table("captcha_analytics_logs") \
            .delete() \
            .lt("created_at", seven_days_ago) \
            .execute()
            
        print(f"Cleanup complete. Permanently deleted {len(old_logs)} old logs from DB.")

    except Exception as e:
        print(f"Error in cleanup_old_captcha_logs: {e}")

# Scheduler Instance
scheduler = BackgroundScheduler()
scheduler.add_job(cleanup_old_captcha_logs, 'cron', hour=2, minute=0)  # Runs daily at 2:00 AM



